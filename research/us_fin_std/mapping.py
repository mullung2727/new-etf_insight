def tag_to_item() -> dict[str, tuple[str, int]]:
    """태그 → (항목, 우선순위 index)."""
    out: dict[str, tuple[str, int]] = {}
    for item, g in GROUPS.items():
        for i, tag in enumerate(g["tags"]):
            if tag in out:
                raise ValueError(f"중복 태그: {tag} ({out[tag][0]}, {item})")
            out[tag] = (item, i)
    return out

def ticker_name(ticker: str) -> str:
    try:
        text = request_text(f"https://finance.naver.com/item/main.naver?code={ticker}")
        match = re.search(r"<title>\s*(.*?)\s*[:：]", text, re.I | re.S)
        if match:
            return clean_text(match.group(1))
    except Exception:
        pass
    return ticker


def relevant_items(items: list[LinkItem], name: str, ticker: str, limit: int, fallback: bool = True) -> list[LinkItem]:
    tokens = {name.lower(), ticker.lower()}
    out = []
    for item in items:
        haystack = f"{item.title} {item.description or ''}".lower()
        if any(token and token in haystack for token in tokens):
            out.append(item)
    return unique_items(out or (items if fallback else []), limit)


def normalize_date(value: str | None) -> str | None:
    if not value:
        return None
    digits = re.sub(r"\D", "", value)
    if len(digits) != 8:
        raise ValueError(f"date must be YYYYMMDD or YYYY-MM-DD: {value}")
    return digits


def dashed_date(yyyymmdd: str) -> str:
    return f"{yyyymmdd[:4]}-{yyyymmdd[4:6]}-{yyyymmdd[6:]}"



@dataclass
class LinkItem:
    title: str
    link: str | None = None
    description: str | None = None


class AnchorParser(HTMLParser):
    def __init__(self, href_pattern: str | None = None) -> None:
        super().__init__()
        self.href_pattern = href_pattern
        self._current_href: str | None = None
        self._current_text: list[str] = []
        self.items: list[LinkItem] = []

    def handle_starttag(self, tag: str, attrs: list[tuple[str, str | None]]) -> None:
        if tag.lower() != "a":
            return
        attrs_dict = dict(attrs)
        href = attrs_dict.get("href") or ""
        if self.href_pattern and not re.search(self.href_pattern, href):
            return
        self._current_href = href
        self._current_text = []

    def handle_data(self, data: str) -> None:
        if self._current_href is not None:
            self._current_text.append(data)

    def handle_endtag(self, tag: str) -> None:
        if tag.lower() != "a" or self._current_href is None:
            return
        title = clean_text(" ".join(self._current_text))
        if title:
            self.items.append(LinkItem(title=title, link=self._current_href))
        self._current_href = None
        self._current_text = []


class TextExtractor(HTMLParser):
    def __init__(self) -> None:
        super().__init__()
        self.parts: list[str] = []
        self._skip_depth = 0

    def handle_starttag(self, tag: str, attrs: list[tuple[str, str | None]]) -> None:
        if tag.lower() in {"script", "style", "noscript"}:
            self._skip_depth += 1

    def handle_endtag(self, tag: str) -> None:
        if tag.lower() in {"script", "style", "noscript"} and self._skip_depth:
            self._skip_depth -= 1

    def handle_data(self, data: str) -> None:
        if not self._skip_depth:
            self.parts.append(data)

    def text(self) -> str:
        return clean_text(" ".join(self.parts))


def clean_text(value: str) -> str:
    value = html.unescape(re.sub(r"<[^>]+>", " ", value or ""))
    value = re.sub(r"\s*\[\d+\]\s*$", "", value)
    return " ".join(value.split())


def html_text(value: str) -> str:
    parser = TextExtractor()
    parser.feed(value or "")
    return parser.text()


def compact_join(parts: list[str], sep: str = ", ") -> str:
    return sep.join(part for part in parts if part)


def usable_board_description(value: str | None) -> bool:
    if not value:
        return False
    noise = ("Npay 증권", "메인 메뉴", "자동완성", "@code@", "시가총액", "호가10단계")
    return not any(marker in value for marker in noise)


def unique_items(items: list[LinkItem], limit: int) -> list[LinkItem]:
    seen: set[str] = set()
    out: list[LinkItem] = []
    for item in items:
        key = clean_text(item.title)
        if not key or key in seen:
            continue
        seen.add(key)
        out.append(item)
        if len(out) >= limit:
            break
    return out


def request_text(url: str, **kwargs) -> str:
    res = requests.get(url, headers=HEADERS, timeout=kwargs.pop("timeout", 15), **kwargs)
    res.raise_for_status()
    if not res.encoding or res.encoding.lower() in {"iso-8859-1", "ascii"}:
        res.encoding = res.apparent_encoding or "utf-8"
    return res.text


def fetch_board_detail(link: str | None, title: str) -> str | None:
    if not link:
        return None
    try:
        text = html_text(request_text(link, timeout=10))
    except Exception:
        return None
    if not text:
        return None
    title_pos = text.find(title)
    if title_pos >= 0:
        text = text[title_pos + len(title):]
    for pattern in (
        r"네이버페이.*",
        r"로그인.*",
        r"증권 고객센터.*",
        r"Copyright.*",
    ):
        text = re.sub(pattern, " ", text, flags=re.I)
    text = clean_text(text)
    for marker in ("투자정보", "목록 이전", "목록 다음", "이전 글", "다음 글"):
        if marker in text:
            text = text.split(marker, 1)[0].strip()
    return text[:260] if text else None


def fetch_board(ticker: str, limit: int = 8) -> list[LinkItem]:
    try:
        text = request_text(f"https://finance.naver.com/item/board.naver?code={ticker}")
        parser = AnchorParser(r"/item/board_read\.naver")
        parser.feed(text)
        for item in parser.items:
            item.link = urljoin("https://finance.naver.com", item.link or "")
        items = unique_items(parser.items, limit)
        for item in items[:5]:
            item.description = fetch_board_detail(item.link, item.title)
        return items
    except Exception as exc:
        return [LinkItem(title=f"조사 실패: {exc}")]


def fetch_naver_stock_news(ticker: str, limit: int = 5) -> list[LinkItem]:
    try:
        text = request_text(f"https://finance.naver.com/item/news_news.naver?code={ticker}&page=1")
        parser = AnchorParser(r"/item/news_read\.naver")
        parser.feed(text)
        for item in parser.items:
            item.link = urljoin("https://finance.naver.com", item.link or "")
        return unique_items(parser.items, limit)
    except Exception:
        return []


def fetch_google_news(query: str, limit: int = 5) -> list[LinkItem]:
    try:
        text = request_text(
            "https://news.google.com/rss/search",
            params={"q": query, "hl": "ko", "gl": "KR", "ceid": "KR:ko"},
            timeout=20,
        )
        root = ET.fromstring(text.encode("utf-8"))
        items = []
        for node in root.findall(".//item"):
            title = clean_text(node.findtext("title") or "")
            link = clean_text(node.findtext("link") or "")
            if title:
                items.append(LinkItem(title=title, link=link))
        return unique_items(items, limit)
    except Exception as exc:
        return [LinkItem(title=f"뉴스 조사 실패: {exc}")]


